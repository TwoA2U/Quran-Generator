// ── Main generate ────────────────────────────────────────────────────────────

async function generate() {
  btnGenerate.disabled = true;
  btnGenerate.classList.add("loading");
  progressCard.style.display = "block";

  const opts = {
    showPage: optPage.checked,
    showLatin: optLatin.checked,
    editionScript: editionScriptInput.value,
    editionTranslation: editionTranslationInput.value,
    fontName: optFont.value,
  };
  const filename = (optFilename.value.trim() || "AlQuran-Kindle") + ".epub";
  const total = 114;

  try {
    setProgress(2, "Memuat metadata surah...", "");
    const surahs = await loadSurahList();

    setProgress(
      8,
      "Memuat font Arab...",
      optFont.options[optFont.selectedIndex].text,
    );

    const FONT_LABELS = {
      "scheherazade-new-arabic-400-normal": "Scheherazade New",
      "amiri-quran-400-normal": "Amiri Quran",
      "quran-complex-ver2-arabic-400-normal": "Quran Complex Font Version 2",
      "kfgqpc-hafs-uthmanic-script-arabic-400-normal":
        "KFGQPC Uthmanic HAFS Script",
      "kfgqpc-hafs-smart-400-normal": "KFGQPC Hafs Smart",
      "noto-naskh-arabic-400-normal": "Noto Naskh Arabic",
    };

    const fontFile = `${opts.fontName}.ttf`;
    const fontPath = `${import.meta.env.BASE_URL}fonts/${fontFile}`;
    const fontFamilyName = FONT_LABELS[opts.fontName] || "Arabic Font";

    try {
      const fontRes = await fetch(fontPath);
      if (!fontRes.ok) throw new Error(`HTTP ${fontRes.status}`);
      const fontBuf = await fontRes.arrayBuffer();
      if (fontBuf.byteLength < 1000) throw new Error(`File font terlalu kecil`);
      setProgress(
        12,
        `Font ${fontFamilyName} berhasil dimuat ✓`,
        `${(fontBuf.byteLength / 1024).toFixed(0)} KB`,
      );
    } catch (e) {
      console.error("Font gagal dimuat:", e);
      setProgress(12, `⚠️ Font ${fontFamilyName} gagal dimuat`, e.message);
      await new Promise((r) => setTimeout(r, 2000));
    }

    const css = buildEpubCss(fontFile, fontFamilyName);

    setProgress(18, "Memuat teks Arab...", `script/${opts.editionScript}.json`);
    const scriptMap = await loadScriptJson(opts.editionScript);

    let latinMap = null;
    if (opts.showLatin) {
      setProgress(
        35,
        "Memuat transliterasi latin...",
        `translation/${TRANSLITERATION_FILE}.json`,
      );
      latinMap = await loadTranslationJson(TRANSLITERATION_FILE);
    }

    let translationMap = null;
    if (opts.editionTranslation) {
      setProgress(
        50,
        "Memuat terjemahan...",
        `translation/${opts.editionTranslation}.json`,
      );
      translationMap = await loadTranslationJson(opts.editionTranslation);
    }

    setProgress(60, "Menggabungkan data ayat...", "");
    const verseDataMap = buildVerseDataMap(
      scriptMap,
      latinMap,
      translationMap,
      surahs,
    );

    setProgress(65, "Menyusun konten EPUB...", "");
    const surahMetaMap = Object.fromEntries(surahs.map((s) => [s.surah_id, s]));
    const sortedNums = Array.from({ length: total }, (_, i) => i + 1);

    const chapters = sortedNums.map((num, i) => {
      const meta = surahMetaMap[num];
      const verses = verseDataMap[num];
      const surahMeta = {
        num,
        name: meta.surah_name,
        nameAr: meta.surah_name_arabic.trim(),
        nameBahasa: meta.surah_name_bahasa,
        revType: MAKKIYAH.has(num) ? "Makkiyah" : "Madaniyah",
        verseCount: meta.surah_verse_count,
      };
      const pct = 65 + ((i + 1) / total) * 20;
      setProgress(
        pct,
        "Menyusun konten...",
        `Surah ${num}: ${meta.surah_name}`,
      );
      return {
        title: `${num}. ${meta.surah_name} (${meta.surah_name_arabic.trim()})`,
        content: buildSurahHtml(surahMeta, verses, opts),
        filename: `surah_${String(num).padStart(3, "0")}.xhtml`,
      };
    });

    setProgress(
      88,
      "Membuat file EPUB...",
      "Ini mungkin membutuhkan beberapa detik",
    );

    const blob = await epub(
      {
        title: "Al-Quran Al-Karim - Latin Transliteration",
        author: "Allah",
        publisher: "",
        cover:
          "https://m.media-amazon.com/images/S/compressed.photo.goodreads.com/books/1275263838i/646462.jpg",
        description: `The Quran (English pronunciation: /kɔrˈɑːn/; Arabic: القرآن‎ al-qurʾān, IPA: [qurˈʔaːn], literally meaning "the recitation"), also transliterated Qur'an, Koran, Al-Coran, Coran, Kur'an, and Al-Qur'an, is the central religious text of Islam, which Muslims believe to be the verbatim word of God (Arabic: الله‎, Allah).
        The Quran is composed of verses (Ayat) that make up 114 chapters (suras) of unequal length which are classified either as Meccan (المكية) or Medinan (المدنية) depending upon the place and time of their claimed revelation. Muslims believe the Quran to be verbally revealed through the angel Jibrīl (Gabriel) from God to Muhammad gradually over a period of approximately 23 years beginning on 22 December 609 CE, when Muhammad was 40, and concluding in 632 CE, the year of his death.
        Muslims regard the Quran as the main miracle of Muhammad, the proof of his prophethood and the culmination of a series of divine messages that started with the messages revealed to Adam, regarded in Islam as the first prophet, and continued with Suhuf Ibrahim (Scrolls of Abraham), the Tawrat (Torah or Pentateuch) of Moses, the Zabur (Tehillim or Book of Psalms) of David, and the Injil (Gospel) of Jesus. The Quran assumes familiarity with major narratives recounted in Jewish and Christian scriptures, summarizing some, dwelling at length on others and in some cases presenting alternative accounts and interpretations of events. The Quran describes itself as a book of guidance, sometimes offering detailed accounts of specific historical events, and often emphasizing the moral significance of an event over its narrative sequence.`,
        lang: "",
        tocTitle: "Daftar Surah",
        css,
        numberChaptersInTOC: false,
        prependChapterTitles: false,
        version: 3,
        fonts: [{ filename: `${opts.fontName}.ttf`, url: fontPath }],
      },
      chapters,
    );

    // Post-process: inject Goodreads + Amazon identifiers into the OPF
    const zip = await JSZip.loadAsync(blob);
    const opfPath = "OEBPS/content.opf";
    const opfFile = zip.file(opfPath);
    if (opfFile) {
      let opfContent = await opfFile.async("string");
      opfContent = opfContent.replace(
        "</metadata>",
        `<dc:identifier id="goodreads">goodreads:646462</dc:identifier>
         <dc:identifier id="amazon">amazon:B0DTR624WB</dc:identifier>
        </metadata>`,
      );
      zip.file(opfPath, opfContent);
    }

    const finalBlob = await zip.generateAsync({
      type: "blob",
      mimeType: "application/epub+zip",
    });

    setProgress(100, "Selesai! Mengunduh...", filename);

    const url = URL.createObjectURL(finalBlob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    setTimeout(() => URL.revokeObjectURL(url), 5000);

    setTimeout(() => {
      progressTitle.textContent = "EPUB berhasil dibuat!";
      progressDetail.textContent = `${total} surah - ${filename}`;
    }, 500);
  } catch (err) {
    console.error(err);
    setProgress(0, "Gagal membuat EPUB", err.message);
  } finally {
    btnGenerate.disabled = false;
    btnGenerate.classList.remove("loading");
  }
}

btnGenerate.addEventListener("click", generate);

// Populate dropdowns from local file lists on load
populateDropdowns();
