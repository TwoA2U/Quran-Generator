/**
 * Loads public/data/translations.json (generated by quranEpubGenerator.py --gen-manifest)
 * Each entry: { file, iso, language, name }
 * Dropdown label: "<Language> - <Translator>"  e.g. "English - Sahih International"
 * Dropdown value: file (filename without .json)
 */
async function populateDropdowns() {
  editionScriptInput.innerHTML = "";
  AVAILABLE_SCRIPTS.forEach((name) => {
    const opt = document.createElement("option");
    opt.value = name;
    opt.textContent = name;
    editionScriptInput.appendChild(opt);
  });

  editionTranslationInput.innerHTML =
    '<option value="">Tanpa terjemahan</option>';
  try {
    const res = await fetch("./data/translations.json");
    if (!res.ok) throw new Error(`translations.json not found (${res.status})`);
    const translations = await res.json();

    translations.forEach(({ file, language, name }) => {
      const opt = document.createElement("option");
      opt.value = file;
      // Split display: "English - Sahih International"
      opt.textContent = name ? `${language} - ${name}` : language;
      editionTranslationInput.appendChild(opt);
    });
  } catch (err) {
    console.warn("Failed to load translations.json:", err);
    const opt = document.createElement("option");
    opt.value = "";
    opt.textContent = "⚠ translations.json not found — run --gen-manifest";
    opt.disabled = true;
    editionTranslationInput.appendChild(opt);
  }
}

// ── Local JSON loaders ──────────────────────────────────────────────────────

/**
 * Load a script JSON from public/script/<name>.json
 * Format: flat array → [{surahId, ayahId, script}, ...]
 * Returns: Map keyed by "surahId:ayahId" → script text
 */
async function loadScriptJson(name) {
  const res = await fetch(`./script/${name}.json`);
  if (!res.ok)
    throw new Error(`Script file not found: public/script/${name}.json`);
  const data = await res.json();
  const map = new Map();
  for (const entry of data) {
    map.set(`${entry.surahId}:${entry.ayahId}`, entry.script);
  }
  return map;
}

/**
 * Load a translation JSON from public/translation/<name>.json
 * Format: nested dict → {"1": [{surah_id, ayah_id, text}, ...], ...}
 * Returns: Map keyed by "surahId:ayahId" → text
 */
async function loadTranslationJson(name) {
  const res = await fetch(`./translation/${name}.json`);
  if (!res.ok)
    throw new Error(
      `Translation file not found: public/translation/${name}.json`,
    );
  const data = await res.json();
  const map = new Map();
  for (const [surahId, ayahs] of Object.entries(data)) {
    for (const ayah of ayahs) {
      map.set(`${surahId}:${ayah.ayah_id}`, {
        text: stripHtml(ayah.text),
        page_number: ayah.page_id ?? null,
      });
    }
  }
  return map;
}

/**
 * Load surah metadata from public/data/surah.json
 */
async function loadSurahList() {
  const res = await fetch("./data/surah.json");
  if (!res.ok) throw new Error(`Surah metadata not found (${res.status})`);
  return await res.json();
}

/**
 * Merge script + transliteration + translation maps into per-surah verse arrays.
 * Returns: { [surahNumber]: [{ayah_number, script, latin, translation}, ...] }
 */
function buildVerseDataMap(scriptMap, latinMap, translationMap, surahList) {
  const verseDataMap = {};

  for (const surah of surahList) {
    const surahId = String(surah.surah_id);
    const verses = [];

    for (let ayahNum = 1; ayahNum <= surah.surah_verse_count; ayahNum++) {
      const key = `${surahId}:${ayahNum}`;
      const translationEntry = translationMap
        ? (translationMap.get(key) ?? null)
        : null;
      const latinEntry = latinMap ? (latinMap.get(key) ?? null) : null;

      verses.push({
        ayah_number: ayahNum,
        page_number:
          translationEntry?.page_number ?? latinEntry?.page_number ?? null,
        script: scriptMap.get(key) ?? "",
        latin: latinEntry?.text ?? "",
        translation: translationEntry?.text ?? "",
      });
    }

    verseDataMap[surah.surah_id] = verses;
  }

  return verseDataMap;
}

// ── Helpers ─────────────────────────────────────────────────────────────────

function setProgress(pct, title, detail = "") {
  progressCard.style.display = "block";
  progressBar.style.width = pct + "%";
  progressPct.textContent = Math.round(pct) + "%";
  progressTitle.textContent = title;
  progressDetail.textContent = detail;
}

function escapeHtml(value = "") {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function stripHtml(value = "") {
  const doc = new DOMParser().parseFromString(String(value), "text/html");
  return doc.body.textContent || "";
}

function buildEpubCss(fontFile, fontFamilyName = "Arabic Font") {
  const fontFace = `@font-face {
    font-family: "${fontFamilyName}";
    font-weight: 400;
    font-style: normal;
    src: url(fonts/${fontFile}) format("truetype");
  }`;

  return `
    ${fontFace}
    body { font-family: serif; margin: 1em; padding: 0; }
    .surah-header { text-align: center; margin-bottom: 1.2em; padding: 0.6em 0;
      border-top: 1px solid #000; border-bottom: 1px solid #000; }
    .surah-number { font-size: 0.85em; font-weight: bold; display: block; margin-bottom: 0.3em; }
    .surah-name-arabic { font-family: "${fontFamilyName}", "Scheherazade New", "Traditional Arabic", serif;
      font-size: 2em; direction: rtl; display: block; margin: 0.2em 0; }
    .surah-name-latin { font-size: 1.05em; font-weight: bold; display: block; }
    .surah-meta { font-size: 0.8em; display: block; margin-top: 0.3em; }
    .basmalah { font-family: "${fontFamilyName}", "Scheherazade New", "Traditional Arabic", serif;
      font-size: 1.35em; line-height: 1.8; direction: rtl; text-align: center; margin: 1em 0; }
    .ayah-block { margin-bottom: 1.2em; padding-bottom: 0.8em; border-bottom: 1px solid #ccc; }
    .ayah-block:last-child { border-bottom: none; }
    .ayah-meta { font-size: 0.78em; line-height: 1; font-weight: bold; margin-bottom: 0.35em; }
    .arabic-text { font-family: "${fontFamilyName}", "Scheherazade New", "Traditional Arabic", serif;
      font-size: 2em; line-height: 1.4; direction: rtl; text-align: right; display: block; margin-bottom: 0.35em; }
    .latin-line { font-size: 0.85em; line-height: 1.2; }
    .translation-line { font-size: 0.85em; line-height: 1.2; margin-top: 0.25em; }
  `;
}

function buildSurahHtml(surahMeta, verses, opts) {
  const { num, name, nameAr, nameBahasa, revType, verseCount } = surahMeta;
  const basmalahText = "بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ";
  const basmalahHtml =
    num !== 1 && num !== 9 ? `<p class="basmalah">${basmalahText}</p>` : "";

  const blocks = verses
    .map((v) => {
      const pageText =
        opts.showPage && v.page_number ? ` - Hal. ${v.page_number}` : "";
      const script =
        num !== 1 && num !== 9 && v.ayah_number === 1
          ? v.script.replace(
              /^﻿?بِسْمِ\s+ٱللَّهِ\s+ٱلرَّحْمَٰنِ\s+ٱلرَّحِيمِ\s*/u,
              "",
            )
          : v.script;
      const latinHtml =
        opts.showLatin && v.latin
          ? `<p class="latin-line">${escapeHtml(v.latin)}</p>`
          : "";
      const translationHtml =
        opts.editionTranslation && v.translation
          ? `<p class="translation-line">${escapeHtml(v.translation)}</p>`
          : "";

      return `
      <div class="ayah-block">
        <p class="ayah-meta">${escapeHtml(name)} - Ayat ${v.ayah_number}${pageText}</p>
        <p class="arabic-text">${escapeHtml(script)}</p>
        ${latinHtml}
        ${translationHtml}
      </div>`;
    })
    .join("\n");

  return `
    <div class="surah-header">
      <p class="surah-number">Surah ${num}</p>
      <p class="surah-name-arabic">${escapeHtml(nameAr)}</p>
      <p class="surah-name-latin">${escapeHtml(name)} - ${escapeHtml(nameBahasa)}</p>
      <p class="surah-meta">${revType} - ${verseCount} Ayat</p>
    </div>
    ${basmalahHtml}
    ${blocks}
  `;
}

